package cli

import (
	"bufio"
	"errors"
	"fmt"
	"io/fs"
	"os"
	"os/exec"
	"path/filepath"
	"strings"

	kaasassets "github.com/Stellar-Technology-Services/kaas"

	"github.com/spf13/cobra"
)

// defaultAnsibleRepo is cloned into <workspace>/ansible when kaas init seeds
// a fresh Ansible tree.
const defaultAnsibleRepo = "https://github.com/Stellar-Technology-Services/ansible"

// initAssets holds root workspace templates (config example + SecretSpec
// manifest). Ansible is seeded by cloning a git repository instead.
var initAssets = kaasassets.Assets

func newInitCmd() *cobra.Command {
	var dir string
	var ansibleRepo string
	cmd := &cobra.Command{
		Use:   "init",
		Short: "Initialize the per-user kaas working directory",
		RunE: func(cmd *cobra.Command, args []string) error {
			return runInit(cmd, dir, ansibleRepo)
		},
	}
	cmd.Flags().StringVar(&dir, "dir", "", "working directory (default: ~/.kaas)")
	cmd.Flags().StringVar(&ansibleRepo, "ansible-repo", "", "git URL to clone into ansible/ (default: "+defaultAnsibleRepo+"; prompted when interactive)")
	return cmd
}

func runInit(cmd *cobra.Command, dir, ansibleRepo string) error {
	if dir == "" {
		home, err := os.UserHomeDir()
		if err != nil {
			return err
		}
		dir = filepath.Join(home, ".kaas")
	}
	dir, err := filepath.Abs(dir)
	if err != nil {
		return err
	}
	if err := os.MkdirAll(dir, 0755); err != nil {
		return fmt.Errorf("create kaas directory: %w", err)
	}
	err = fs.WalkDir(initAssets, ".", func(path string, d fs.DirEntry, walkErr error) error {
		if walkErr != nil {
			return walkErr
		}
		if d.IsDir() {
			return nil
		}
		rel, _ := filepath.Rel(".", path)
		// kaas.yaml is generated from kaas.example.yaml below.
		if rel == "kaas.example.yaml" {
			return nil
		}
		dst := filepath.Join(dir, rel)
		if err := os.MkdirAll(filepath.Dir(dst), 0755); err != nil {
			return err
		}
		data, err := initAssets.ReadFile(path)
		if err != nil {
			return err
		}
		if _, err := os.Stat(dst); err == nil {
			return nil
		}
		if err := os.WriteFile(dst, data, 0644); err != nil {
			return err
		}
		return nil
	})
	if err != nil {
		return fmt.Errorf("install workspace assets: %w", err)
	}
	cfg := filepath.Join(dir, "kaas.yaml")
	if _, err := os.Stat(cfg); errors.Is(err, os.ErrNotExist) {
		data, _ := initAssets.ReadFile("kaas.example.yaml")
		data = []byte("# Generated by kaas init. Ansible paths are relative to this directory.\n" + string(data))
		data = []byte(strings.ReplaceAll(string(data), "ansible_dir: .", "ansible_dir: ansible"))
		if err := os.WriteFile(cfg, data, 0644); err != nil {
			return err
		}
	}

	ansibleDir := filepath.Join(dir, "ansible")
	clonedFrom, err := seedAnsibleRepo(cmd, ansibleDir, ansibleRepo)
	if err != nil {
		return err
	}

	printStyled(cmd, styleSuccess, "Initialized kaas in %s\n", dir)
	if clonedFrom != "" {
		printMessage(cmd, "  Ansible files: %s (cloned from %s)\n", ansibleDir, clonedFrom)
	} else {
		printMessage(cmd, "  Ansible files: %s (preserved)\n", ansibleDir)
	}
	printMessage(cmd, "  Config: %s\n", cfg)
	printMessage(cmd, "  State: %s\n", filepath.Join(dir, "state.db"))
	printStyled(cmd, styleInfo, "Next: kaas deps --install && kaas up <name>\n")
	return nil
}

// seedAnsibleRepo clones ansibleRepo into ansibleDir when the directory does
// not already exist. Returns the URL that was cloned, or "" when preserved.
func seedAnsibleRepo(cmd *cobra.Command, ansibleDir, ansibleRepo string) (string, error) {
	if _, err := os.Stat(ansibleDir); err == nil {
		return "", nil
	} else if !errors.Is(err, os.ErrNotExist) {
		return "", fmt.Errorf("check ansible directory: %w", err)
	}

	url := strings.TrimSpace(ansibleRepo)
	if url == "" {
		resolved, err := promptAnsibleRepo(cmd)
		if err != nil {
			return "", err
		}
		url = resolved
	}

	if _, err := exec.LookPath("git"); err != nil {
		return "", fmt.Errorf("git is required to seed ansible/; install git and retry")
	}

	c := exec.Command("git", "clone", url, ansibleDir)
	c.Stdout = commandOutput(cmd)
	c.Stderr = os.Stderr
	if err := c.Run(); err != nil {
		return "", fmt.Errorf("git clone %s into %s: %w", url, ansibleDir, err)
	}
	return url, nil
}

func promptAnsibleRepo(cmd *cobra.Command) (string, error) {
	if !stdinIsInteractive() {
		return defaultAnsibleRepo, nil
	}
	fmt.Fprintf(commandOutput(cmd), "Ansible git repository [%s]: ", defaultAnsibleRepo)
	answer, err := bufio.NewReader(os.Stdin).ReadString('\n')
	if err != nil && len(answer) == 0 {
		// EOF with no input — use default (same as non-interactive).
		return defaultAnsibleRepo, nil
	}
	answer = strings.TrimSpace(answer)
	if answer == "" {
		return defaultAnsibleRepo, nil
	}
	return answer, nil
}

func stdinIsInteractive() bool {
	fi, err := os.Stdin.Stat()
	if err != nil {
		return false
	}
	return fi.Mode()&os.ModeCharDevice != 0
}
